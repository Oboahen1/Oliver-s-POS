export const icon = (n, cls = '') => `<svg class="i ${cls}" viewBox="0 0 24 24" aria-hidden="true">${P[n] || ''}</svg>`;

/* ---------- Toasts (polite live region) ---------- */
export function toast(msg, type = 'ok') {
  let box = document.getElementById('toasts');
  if (!box) { box = document.createElement('div'); box.id = 'toasts'; box.setAttribute('aria-live', 'polite'); document.body.appendChild(box); }
  const el = document.createElement('div');
  el.className = 'toast ' + type;
  el.innerHTML = icon(type === 'err' ? 'alert' : 'checkc') + `<span>${esc(msg)}</span>`;
  box.appendChild(el);
  setTimeout(() => el.remove(), type === 'err' ? 5000 : 3200);
}

/* ---------- Dialogs (native <dialog>: focus trap + Esc for free) ---------- */
export function dialog(html, cls = '') {
  const d = document.createElement('dialog');
  d.className = 'dlg ' + cls;
  d.innerHTML = html;
  document.body.appendChild(d);
  d.addEventListener('close', () => d.remove());
  d.addEventListener('click', e => { if (e.target === d || e.target.closest('[data-close]')) d.close(); });
  d.showModal();
  return d;
}
export const closeDialogs = () => document.querySelectorAll('dialog[open]').forEach(d => d.close());

export function confirmDialog({ title, message, confirm = 'Confirm', danger = false }) {
  return new Promise(resolve => {
    let ok = false;
    const d = dialog(`<div class="dlg-box"><h2>${esc(title)}</h2><p class="sub">${esc(message)}</p>
      <div class="dlg-actions"><button class="btn" data-close>Cancel</button>
      <button class="btn ${danger ? 'danger solid' : 'primary'}" id="cfm">${esc(confirm)}</button></div></div>`, 'narrow');
    d.querySelector('#cfm').addEventListener('click', () => { ok = true; d.close(); });
    d.addEventListener('close', () => resolve(ok));
  });
}

/* ---------- Small helpers ---------- */
export const initials = n => String(n || '?').trim().split(/[\s._-]+/).slice(0, 2).map(w => w[0]).join('').toUpperCase() || '?';
export const hue = s => [...String(s)].reduce((a, c) => (a * 31 + c.charCodeAt(0)) % 360, 7);
export const avatar = (name, cls = '') => `<div class="avatar ${cls}" style="background:hsl(${hue(name)} 52% 40%)" aria-hidden="true">${esc(initials(name))}</div>`;

export function setBusy(btn, on, label) {
  if (!btn) return;
  if (on) { btn.dataset.html = btn.innerHTML; btn.disabled = true; btn.innerHTML = `<span class="spin"></span><span>${esc(label || 'Please wait…')}</span>`; }
  else { btn.disabled = false; if (btn.dataset.html) btn.innerHTML = btn.dataset.html; }
}
